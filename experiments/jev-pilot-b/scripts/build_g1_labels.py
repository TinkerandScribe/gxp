def main() -> None:
    if len(ROWS) != 120:
        raise SystemExit(f"expected 120 tuples, got {len(ROWS)}")
    rows = [
        LabelRow(
            id=rid,
            artifact=artifact,
            criterion=criterion,
            gold=gold,  # type: ignore[arg-type]
            split=split,  # type: ignore[arg-type]
            source_tag=tag,
        )
        for rid, tag, split, gold, artifact, criterion in ROWS
    ]
    jsonl = ROOT / "data" / "labels.jsonl"
    csv_path = ROOT / "data" / "labels.csv"
    write_jsonl(jsonl, rows)
    write_csv(csv_path, rows)
    print(f"wrote {len(rows)} rows → {jsonl.relative_to(ROOT)} and {csv_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
